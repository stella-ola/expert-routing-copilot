// Runs the golden and held-out sets, writes data/eval-results.{json,md}, and reports regression and readiness gates.
//   node evals/run-evals.mjs          rules extractor (no API key needed; this is what CI runs)
//   node evals/run-evals.mjs --llm    LLM extractor, same policy (needs ANTHROPIC_API_KEY)

import { writeFileSync, mkdirSync } from 'node:fs';
import { evaluate, extractFeatures, decide, DEFAULT_CONFIG } from '../docs/app/engine.js';
import { GOLDEN_SET, HELDOUT_SET } from '../docs/app/golden-set.js';

const useLLM = process.argv.includes('--llm');

// The regression gate protects behavior already established on the tuned baseline.
// It is not a launch-readiness claim. Readiness is evaluated on held-out cases.
const REGRESSION_GATE = { p0RecallGated: 100, exactMatchGated: 90 };
const READINESS_GATE = {
  p0Recall: { op: 'min', value: 100 },
  exactMatch: { op: 'min', value: 80 },
  reachedHumanWhenNeeded: { op: 'min', value: 98 },
  overEscalation: { op: 'max', value: 15 },
};

async function run(set) {
  if (!useLLM) return evaluate(set);
  const { llmExtract } = await import('./llm-extractor.mjs');
  const cache = new Map();
  for (const c of set) cache.set(c.id, await llmExtract(c.message));
  // evaluate() takes a sync extractor; resolve LLM calls first, then reuse the same scoring path.
  const byMsg = new Map(set.map((c) => [c.message, cache.get(c.id)]));
  return evaluate(set, DEFAULT_CONFIG, (msg) => byMsg.get(msg));
}

const extractor = useLLM ? 'llm' : 'rules';
const golden = await run(GOLDEN_SET);
const heldout = await run(HELDOUT_SET);

const regressionChecks = Object.entries(REGRESSION_GATE).map(([metric, min]) => ({ metric, operator: '>=', threshold: min, actual: golden.summary[metric], pass: golden.summary[metric] >= min }));
const readinessChecks = Object.entries(READINESS_GATE).map(([metric, rule]) => {
  const actual = heldout.summary[metric];
  const pass = rule.op === 'min' ? actual >= rule.value : actual <= rule.value;
  return { metric, operator: rule.op === 'min' ? '>=' : '<=', threshold: rule.value, actual, pass };
});
const regressionPassed = regressionChecks.every((check) => check.pass);
const readinessPassed = readinessChecks.every((check) => check.pass);

mkdirSync('data', { recursive: true });
const out = {
  extractor,
  ranAt: new Date().toISOString(),
  regressionGate: { passed: regressionPassed, checks: regressionChecks },
  readinessGate: { passed: readinessPassed, checks: readinessChecks },
  golden: golden.summary,
  heldout: heldout.summary,
  rows: [...golden.rows, ...heldout.rows].map(({ id, tags, message, expect, actual, ok, note }) => ({ id, tags, message, expect, actual, ok, note })),
};
writeFileSync(`data/eval-results-${extractor}.json`, JSON.stringify(out, null, 2));

const fmt = (s) => [
  `| Metric | Value |`, `| --- | --- |`,
  ...[['Cases', s.cases], ['Exact match (team + priority + channel)', s.exactMatch + '%'], ['Exact match, excluding known gaps', s.exactMatchGated + '%'],
    ['Team accuracy', s.teamAccuracy + '%'], ['Priority accuracy', s.priorityAccuracy + '%'], ['Channel accuracy', s.channelAccuracy + '%'],
    ['P0 recall (urgent cases caught)', s.p0Recall + '%'], ['P0 precision', s.p0Precision === null ? 'n/a (no P0 predicted)' : s.p0Precision + '%'],
    ['Reached a human when needed', s.reachedHumanWhenNeeded + '%'], ['Over-escalation', s.overEscalation + '%']].map(([a, b]) => `| ${a} | ${b} |`),
].join('\n');

const misses = out.rows.filter((r) => !r.ok.all).map((r) =>
  `| ${r.id} | ${r.tags.join(', ')} | ${r.message.replace(/\|/g, '/')} | ${r.expect.team} / ${r.expect.priority} / ${r.expect.channel} | ${r.actual.team} / ${r.actual.priority} / ${r.actual.channel} | ${r.note || ''} |`);

const formatChecks = (checks) => checks.map((check) => `${check.metric} ${check.actual}% vs ${check.operator}${check.threshold}%`).join('; ');

const md = `# Eval results (${extractor} extractor)

Generated by \`node evals/run-evals.mjs${useLLM ? ' --llm' : ''}\`. Synthetic data only.

**Regression gate: ${regressionPassed ? 'PASS' : 'FAIL'}** (${formatChecks(regressionChecks)})

**Held-out readiness: ${readinessPassed ? 'READY FOR THE NEXT CONTROLLED STAGE' : 'BLOCKED'}** (${formatChecks(readinessChecks)})

The regression gate prevents changes from breaking the tuned baseline. Held-out readiness determines whether the extractor can be considered for a controlled shadow or assisted stage; it does not authorize production automation.

## Golden set (used to tune the rules)
${fmt(golden.summary)}

## Held-out set (never used for tuning)
${fmt(heldout.summary)}

## Every miss
| ID | Tags | Message | Expected | Actual | Note |
| --- | --- | --- | --- | --- | --- |
${misses.join('\n')}
`;
writeFileSync(`data/eval-results-${extractor}.md`, md);

console.log(md);
if (!regressionPassed) { console.error('Regression gate failed.'); process.exit(1); }
if (useLLM && !readinessPassed) { console.error('Candidate extractor did not clear held-out readiness.'); process.exit(1); }
